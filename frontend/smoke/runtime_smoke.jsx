import React from 'react';
import {createRoot} from 'react-dom/client';
import '@mantine/core/styles.css';
import '../css/style.css';
import '../css/gframe-window.css';
import '../css/duel-original.css';
import '../css/duel-neos.css';
import '../css/ui-kit.css';
import App from '../src/App.tsx';
import {eventBus,WailsBridge} from '../src/wails_bridge.ts';

const smoke=window.__runtimeSmoke={checks:{},ready:false};
const check=(name,ok)=>{smoke.checks[name]=!!ok;};
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const wait=async fn=>{for(let i=0;i<300;i++){if(fn())return;await pause(15);}throw Error('runtime wait timed out');};
const $=selector=>document.querySelector(selector);
const originals={...WailsBridge};
WailsBridge.getCardImage=async()=>({url:'textures/cover.jpg'});
createRoot(document.getElementById('root')).render(<App />);
async function run(){
 await wait(()=>$('.runtime-mode-chip'));
 check('preview-mode-visible',$('.runtime-mode-chip').textContent.includes('浏览器演示'));
 $('.runtime-mode-chip').click();await wait(()=>$('.runtime-help-dialog'));
 check('help-explains-real-engine',$('.runtime-help-dialog').textContent.includes('不能在浏览器里执行 Lua'));
 let copied='';
 Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{copied=text;}}});
 $('.runtime-help-actions button').click();await wait(()=>copied);
 check('desktop-commands-copyable',copied.includes('go run ./cmd/wails')&&copied.includes('fetch_scripts.py'));
 Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw Error('denied');}}});
 $('.runtime-help-actions button').click();await wait(()=>$('.runtime-help-dialog [role=status]')?.textContent.includes('手动选择'));
 check('clipboard-failure-offers-manual-copy',true);
 $('.runtime-help-actions button:last-child').click();await wait(()=>!$('.runtime-help-dialog'));
 $('#menu-btn-single').click();await wait(()=>$('#single-start')&&!$('#single-start').disabled);
 $('#single-start').click();await wait(()=>$('#single-error'));
 check('browser-single-cannot-enter-empty-board',!!$('#single-screen')&&!$('#duel-screen')&&$('#single-error').textContent.includes('浏览器演示'));
 $('#single-exit').click();await wait(()=>$('#main-menu-screen'));
 WailsBridge.listSingles=async()=>{throw Error('offline');};
 $('#menu-btn-single').click();await wait(()=>$('#single-list [role=alert]'));
 check('list-failure-is-explained',$('#single-start').disabled);
 WailsBridge.listSingles=async()=>[];
 $('#single-list button').click();await wait(()=>$('#single-list').textContent.includes('没有找到谜题脚本'));
 check('empty-list-has-resource-path',$('#single-list').textContent.includes('single/')&&$('#single-start').disabled);
 WailsBridge.listSingles=async()=>[{name:'first.lua',message:'one'},{name:'second.lua',message:'two'}];
 $('#single-list button').click();await wait(()=>$('#single-list .gfw-list-item')&&!$('#single-start').disabled);
 let starts=0,startedName='',resolveStart;
 WailsBridge.startSingle=(name)=>{starts++;startedName=name;return new Promise(resolve=>{resolveStart=resolve;});};
 $('#single-list .gfw-list-item:nth-child(2)').dispatchEvent(new MouseEvent('dblclick',{bubbles:true}));
 $('#single-start').click();await pause(25);
 check('start-uses-double-clicked-puzzle-and-locks',starts===1&&startedName==='second.lua'&&$('#single-start').disabled);
 resolveStart({success:false,error:'engine unavailable'});await wait(()=>!$('#single-start').disabled);
 WailsBridge.startSingle=async()=>{throw Error('bridge closed');};
 $('#single-start').click();await wait(()=>$('#single-error')?.textContent.includes('启动失败'));
 check('start-rejection-is-recoverable',!$('#single-start').disabled);
 $('#single-exit').click();await wait(()=>$('#main-menu-screen'));
 WailsBridge.listDecks=async()=>{throw Error('read failed');};
 $('#menu-btn-deck').click();await wait(()=>$('.deck-load-message[role=alert]'));
 check('deck-list-error-visible',$('.deck-load-message').textContent.includes('deck/'));
 WailsBridge.listDecks=async()=>[];
 $('.deck-load-message button').click();await wait(()=>$('.deck-load-message').textContent.includes('还没有卡组'));
 check('deck-empty-explains-how-to-start',$('.deck-load-message').textContent.includes('.ydk'));
 check('search-idle-explains-enter',$('.deck-empty-state').textContent.includes('Enter'));
 WailsBridge.searchCards=async()=>{throw Error('db offline');};
 $('#deck-search-input').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,key:'Enter'}));
 await wait(()=>$('.deck-empty-state[role=alert]'));
 check('search-error-can-retry',$('.deck-empty-state[role=alert]').textContent.includes('cards.cdb'));
 WailsBridge.searchCards=async()=>[];
 $('.deck-empty-state button').click();await wait(()=>$('.deck-empty-state strong')?.textContent==='没有匹配的卡片');
 check('mock-search-empty-explains-limited-data',$('.deck-empty-state').textContent.includes('89631139'));
 // A slow rejected query must not overwrite a newer successful result.
 let rejectOld;
 WailsBridge.searchCards=()=>new Promise((_,reject)=>{rejectOld=reject;});
 $('#deck-search-input').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,key:'Enter'}));await wait(()=>rejectOld);
 WailsBridge.searchCards=async()=>[{code:89631139,name:'Blue-Eyes',type:17,attack:3000,defense:2500,level:8}];
 $('#deck-search-input').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,key:'Enter'}));await wait(()=>$('#deck-result-count').textContent.includes('1'));
 rejectOld(Error('stale'));await pause(40);
 check('stale-error-cannot-replace-new-results',!$('.deck-empty-state[role=alert]')&&$('#deck-result-count').textContent.includes('1'));
 check('no-fatal',true);
}
run().catch(error=>{smoke.checks.fatalMsg=String(error.stack||error);}).finally(()=>{Object.assign(WailsBridge,originals);smoke.ready=true;});
