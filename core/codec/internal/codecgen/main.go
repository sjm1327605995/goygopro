// Command codecgen 把带 codec tag / 标记类型的结构体在构建期翻译成编解码
// 方法（zz_codec_gen.go），替代运行时的反射 plan：生成代码用
// encoding/binary 小端原语直接读写缓冲区，零反射、零 unsafe。
//
// 用法（包内放指令，go generate 执行）：
//
//	//go:generate codecgen          // 扫描包内全部非测试结构体
//	//go:generate codecgen -test    // 只扫描 _test.go 里声明的结构体
//
// 生成范围（候选判定）：带 codec tag（count/if/greedy/skip）或标记字段
// （WireLen8..32 / Count8..32）的结构体，或「全部字段导出且字段类型是
// 定宽整型/bool/定长数组/定宽 slice/指针/嵌套结构体」的候选布局。
// 布局非法的候选类型生成返回校验错误的 stub（Register 期 fail-fast）。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/token"
	"go/types"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
)

const codecPath = "github.com/sjm1327605995/goygopro/core/codec"

var (
	testMode = flag.Bool("test", false, "只扫描 _test.go 中声明的结构体")
	outName  = flag.String("out", "", "输出文件名（默认 zz_codec_gen.go / zz_codec_gen_test.go）")
)

func main() {
	flag.Parse()
	fset := token.NewFileSet()
	cfg := &packages.Config{
		Mode:  packages.NeedName | packages.NeedTypes | packages.NeedSyntax,
		Dir:   ".",
		Tests: *testMode,
		Fset:  fset,
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		log.Fatalf("加载包: %v", err)
	}
	pkg := pickPackage(pkgs)
	if pkg == nil || pkg.Types == nil {
		log.Fatal("未找到目标包")
	}

	g := &gen{
		fset:       fset,
		pkg:        pkg,
		pkgPath:    pkg.Types.Path(),
		pkgName:    pkg.Types.Name(),
		pkgIsCodec: pkg.Types.Path() == codecPath,
	}
	var names []string
	scope := pkg.Types.Scope()
	for _, name := range scope.Names() {
		tn, ok := scope.Lookup(name).(*types.TypeName)
		if !ok || tn.IsAlias() {
			continue
		}
		named, ok := tn.Type().(*types.Named)
		if !ok {
			continue
		}
		if _, ok := named.Underlying().(*types.Struct); !ok {
			continue
		}
		if *testMode && !declaredInTest(fset, tn) {
			continue // 非测试类型由正常模式的生成文件覆盖，避免重复方法
		}
		if !*testMode && !g.candidate(named) {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	var body bytes.Buffer
	needBinary := false
	for _, name := range names {
		if g.emitStruct(&body, name, scope.Lookup(name).(*types.TypeName).Type().(*types.Named)) {
			needBinary = true
		}
	}

	var head bytes.Buffer
	fmt.Fprintf(&head, "// Code generated by codecgen; DO NOT EDIT.\n\npackage %s\n\n", g.pkgName)
	if !g.pkgIsCodec {
		head.WriteString("import \"github.com/sjm1327605995/goygopro/core/codec\"\n\n")
	}
	if needBinary {
		head.WriteString("import \"encoding/binary\"\n\n")
	}
	head.Write(body.Bytes())

	out := *outName
	if out == "" {
		out = "zz_codec_gen.go"
		if *testMode {
			out = "zz_codec_gen_test.go"
		}
	}
	if err := os.WriteFile(out, head.Bytes(), 0644); err != nil {
		log.Fatalf("写 %s: %v", out, err)
	}
	fmt.Printf("codecgen: %s: %d 个类型 -> %s\n", g.pkgPath, len(names), out)
}

// pickPackage 选出目标 *types.Package。x/tools 的测试增强变体与主包
// 同 PkgPath（scope 包含 _test.go 声明），用 scope 规模区分；testmain
// （package main、scope 为空）一律跳过。
func pickPackage(pkgs []*packages.Package) *packages.Package {
	var best *packages.Package
	bestN := -1
	for _, p := range pkgs {
		if p.Types == nil || strings.HasSuffix(p.Types.Path(), ".test") {
			continue
		}
		n := len(p.Types.Scope().Names())
		if n > bestN {
			best, bestN = p, n
		}
	}
	if *testMode {
		return best // scope 最大者即测试增强变体
	}
	for _, p := range pkgs {
		if p == best {
			continue
		}
		if p.Types != nil && !strings.HasSuffix(p.Types.Path(), ".test") && p.Types.Path() == best.Types.Path() && len(p.Types.Scope().Names()) < len(best.Types.Scope().Names()) {
			return p // 正常模式取 scope 较小的（不含测试声明）
		}
	}
	return best
}

func declaredInTest(fset *token.FileSet, tn *types.TypeName) bool {
	return strings.HasSuffix(fset.Position(tn.Pos()).Filename, "_test.go")
}

// ---------------------------------------------------------------------------
// 生成器上下文与类型助手
// ---------------------------------------------------------------------------

type gen struct {
	fset       *token.FileSet
	pkg        *packages.Package
	pkgPath    string
	pkgName    string
	pkgIsCodec bool
	curMeta    *structMeta // 当前构建条目的结构体（计数字段类型查询）
}

func (g *gen) q(n string) string { // 限定 codec 包助手名
	if g.pkgIsCodec {
		return n
	}
	return "codec." + n
}

// basicInfo 报告定宽整型/布尔的线宽与符号性（int/uint/string 不算）。
func basicInfo(t types.Type) (width int, signed, isBool, ok bool) {
	b, isBasic := t.Underlying().(*types.Basic)
	if !isBasic {
		return 0, false, false, false
	}
	switch b.Kind() {
	case types.Bool:
		return 1, false, true, true
	case types.Int8:
		return 1, true, false, true
	case types.Uint8:
		return 1, false, false, true
	case types.Int16:
		return 2, true, false, true
	case types.Uint16:
		return 2, false, false, true
	case types.Int32:
		return 4, true, false, true
	case types.Uint32:
		return 4, false, false, true
	case types.Int64:
		return 8, true, false, true
	case types.Uint64:
		return 8, false, false, true
	}
	return 0, false, false, false
}

// isIntKind 报告类型是否为整型（含平台相关 int/uint，count/if 引用校验用）。
func isIntKind(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	if !ok {
		return false
	}
	switch b.Kind() {
	case types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
		types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64:
		return true
	}
	return false
}

func isUint8(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Kind() == types.Uint8
}

// markerWidth 报告 typ 是否为 codec 包的标记类型（WireLen* / Count*）。
func markerWidth(t types.Type, table map[string]int) (int, bool) {
	n, ok := t.(*types.Named)
	if !ok {
		return 0, false
	}
	obj := n.Obj()
	if obj.Pkg() == nil || obj.Pkg().Path() != codecPath {
		return 0, false
	}
	w, ok := table[obj.Name()]
	return w, ok
}

var wireLenTable = map[string]int{"WireLen8": 1, "WireLen16": 2, "WireLen32": 4}
var countTable = map[string]int{"Count8": 1, "Count16": 2, "Count32": 4}

func isWireLen(t types.Type) (int, bool)     { return markerWidth(t, wireLenTable) }
func isCountMarker(t types.Type) (int, bool) { return markerWidth(t, countTable) }

// isRestType 报告字段类型是否就是 codec.Rest（greedy 的具名类型形式，
// 按类型身份判定）。
func isRestType(t types.Type) bool {
	n, ok := t.(*types.Named)
	if !ok {
		return false
	}
	obj := n.Obj()
	return obj.Pkg() != nil && obj.Pkg().Path() == codecPath && obj.Name() == "Rest"
}

// typeRef 返回类型在生成代码里的书写形式（同包裸名，跨包包名限定）。
func (g *gen) typeRef(t types.Type) string {
	switch u := t.(type) {
	case *types.Named:
		obj := u.Obj()
		if obj.Pkg() == nil || obj.Pkg().Path() == g.pkgPath {
			return obj.Name()
		}
		return obj.Pkg().Name() + "." + obj.Name()
	case *types.Basic:
		return u.Name()
	case *types.Array:
		return fmt.Sprintf("[%d]%s", u.Len(), g.typeRef(u.Elem()))
	case *types.Slice:
		return "[]" + g.typeRef(u.Elem())
	case *types.Pointer:
		return "*" + g.typeRef(u.Elem())
	}
	return t.String()
}

// nestedStructName 取嵌套结构体字段的类型名（校验错误信息 Struct 字段用）。
func nestedStructName(t types.Type, fieldName string) string {
	if n, ok := t.(*types.Named); ok {
		return n.Obj().Name()
	}
	return fieldName
}

// ---------------------------------------------------------------------------
// 结构体元数据与校验（旧 parseMeta/validateType/fixedSize 的 go/types
// 逐行移植，错误消息逐字保留）
// ---------------------------------------------------------------------------

type fieldMeta struct {
	name        string
	typ         types.Type
	count       string // 小写目标字段名，空表示无
	greedy      bool
	rest        bool // 字段类型即 codec.Rest（greedy 的具名类型形式）
	skip        int
	hasSkip     bool
	cond        string // 小写谓词字段名
	mask        uint64
	hasCond     bool
	bit         int // bit:"N" 位号（-1 表示无）
	hasBit      bool
	bitPred     int // bit 谓词字段（声明序向前最近的前导整型字段）在 fields 中的下标
	isWL        bool
	wlWidth     int
	isCM        bool // Count 标记
	cmWidth     int
	countTarget int
	countBound  bool
	boundBy     int
}

type structMeta struct {
	name   string
	fields []*fieldMeta
	byName map[string]int
	st     *types.Struct
}

func fieldKey(name string) string { return strings.ToLower(name) }

// parseStructTags 第一阶段：收集导出字段并解析 tag（对应 parseMeta 前半）。
// bad != nil 表示 tag 语法错误，badMsg 为对应消息。
func parseStructTags(st *types.Struct) (m *structMeta, bad *fieldMeta, badMsg string) {
	m = &structMeta{byName: map[string]int{}}
	for i := 0; i < st.NumFields(); i++ {
		v := st.Field(i)
		if !v.Exported() { // 未导出字段不参与编解码
			continue
		}
		fm := &fieldMeta{name: v.Name(), typ: v.Type(), countTarget: -1, boundBy: -1, bit: -1, bitPred: -1}
		key := fieldKey(v.Name())
		if _, dup := m.byName[key]; dup {
			return nil, fm, "字段名忽略大小写后重复"
		}
		m.byName[key] = len(m.fields)
		if isRestType(v.Type()) {
			fm.rest = true // 字段类型即 codec.Rest：greedy 语义，无需 tag
		}
		tag := st.Tag(i)
		if countTag, ok := lookupTag(tag, "count"); ok && countTag != "" {
			fm.count = fieldKey(strings.TrimSpace(countTag))
		}
		if _, ok := lookupTag(tag, "greedy"); ok {
			fm.greedy = true
		}
		if skipTag, ok := lookupTag(tag, "skip"); ok {
			n, err := strconv.Atoi(strings.TrimSpace(skipTag))
			if err != nil || n < 0 {
				return nil, fm, fmt.Sprintf("skip tag 非法: %q", skipTag)
			}
			fm.skip = n
			fm.hasSkip = true
		}
		if bitTag, ok := lookupTag(tag, "bit"); ok {
			n, err := strconv.Atoi(strings.TrimSpace(bitTag))
			if err != nil || n < 0 {
				return nil, fm, fmt.Sprintf("bit tag 非法: %q", bitTag)
			}
			fm.bit = n
			fm.hasBit = true
		}
		if condTag, ok := lookupTag(tag, "if"); ok {
			name, maskStr, found := strings.Cut(condTag, "&")
			fm.cond = fieldKey(strings.TrimSpace(name))
			if !found || strings.TrimSpace(maskStr) == "" {
				fm.mask = ^uint64(0)
			} else {
				maskVal, err := strconv.ParseUint(strings.TrimSpace(maskStr), 0, 64)
				if err != nil {
					return nil, fm, fmt.Sprintf("if tag 掩码非法: %q", maskStr)
				}
				fm.mask = maskVal
			}
			fm.hasCond = true
		}
		m.fields = append(m.fields, fm)
	}
	return m, nil, ""
}

// lookupTag 解析 struct tag 字符串里的键（reflect 语法）。
func lookupTag(tag, key string) (string, bool) {
	for tag != "" {
		tag = strings.TrimLeft(tag, " ")
		if tag == "" {
			break
		}
		i := 0
		for i < len(tag) && tag[i] > ' ' && tag[i] != ':' && tag[i] != '"' && tag[i] != 0x7f {
			i++
		}
		if i == 0 || i+1 >= len(tag) || tag[i] != ':' || tag[i+1] != '"' {
			break
		}
		name := tag[:i]
		rest := tag[i+1:]
		qvalue, r, ok := quotedPrefix(rest)
		if !ok {
			break
		}
		if key == name {
			return qvalue, true
		}
		tag = r
	}
	return "", false
}

func quotedPrefix(s string) (value, rest string, ok bool) {
	if s == "" || s[0] != '"' {
		return "", s, false
	}
	for i := 1; i < len(s); i++ {
		if s[i] == '\\' {
			i++
			continue
		}
		if s[i] == '"' {
			q, err := strconv.Unquote(s[:i+1])
			if err != nil {
				return "", s[i+1:], false
			}
			return q, s[i+1:], true
		}
	}
	return "", s, false
}

// validate 第二/三阶段：引用关系与类型约束（parseMeta 后半的逐行移植）。
// 返回 (meta, 错误消息, 出错字段)；消息为空表示合法。
func (g *gen) validate(name string, st *types.Struct) (*structMeta, string, *fieldMeta) {
	m, bad, badMsg := parseStructTags(st)
	if bad != nil {
		return nil, badMsg, bad
	}
	m.name = name
	m.st = st
	for _, f := range m.fields {
		if w, ok := isWireLen(f.typ); ok {
			f.isWL, f.wlWidth = true, w
		}
		if w, ok := isCountMarker(f.typ); ok {
			f.isCM, f.cmWidth = true, w
		}
	}
	for i, f := range m.fields {
		fieldType := f.typ
		switch {
		case f.isWL:
			if f.hasCond || f.hasBit || f.count != "" || f.greedy || f.rest || f.hasSkip {
				return nil, "WireLen 字段不能配 if/bit/count/greedy/Rest/skip tag", f
			}
			if i+1 >= len(m.fields) {
				return nil, "WireLen 字段后必须紧跟目标字段（[]byte / 定长结构体 / 定宽元素 slice）", f
			}
			next := m.fields[i+1]
			nextType := next.typ
			if next.hasCond || next.hasBit || next.count != "" || next.greedy || next.rest || next.hasSkip {
				return nil, "WireLen 目标字段不能配 if/bit/count/greedy/Rest/skip tag", next
			}
			switch u := nextType.Underlying().(type) {
			case *types.Slice:
				if !isUint8(u.Elem()) {
					if _, msg := g.fixedSize(u.Elem()); msg != "" {
						return nil, msg, next
					}
				}
			case *types.Struct:
				if _, msg := g.fixedSize(nextType); msg != "" {
					return nil, msg, next
				}
			default:
				return nil, "WireLen 目标字段类型不支持（允许 []byte / 定长结构体 / 定宽元素 slice）", next
			}
			if i+2 < len(m.fields) && (m.fields[i+2].greedy || m.fields[i+2].rest) {
				return nil, "WireLen 目标字段之后不得是 greedy 字段", m.fields[i+2]
			}
		case f.isCM:
			if f.hasCond || f.hasBit || f.count != "" || f.greedy || f.rest || f.hasSkip {
				return nil, "Count 字段不能配 if/bit/count/greedy/Rest/skip tag", f
			}
			// 沿声明序向后扫描，绑定第一个未绑定且非 greedy 的 slice 字段
			bind := -1
			for j := i + 1; j < len(m.fields); j++ {
				if _, ok := m.fields[j].typ.Underlying().(*types.Slice); !ok || m.fields[j].greedy || m.fields[j].rest {
					continue
				}
				if m.fields[j].countBound || m.fields[j].count != "" {
					continue
				}
				bind = j
				break
			}
			if bind == -1 {
				return nil, "Count 字段后必须存在未绑定的 slice 字段（定宽元素）", f
			}
			tf := m.fields[bind]
			if tf.hasCond || tf.hasBit || tf.hasSkip {
				return nil, "Count 目标字段不能配 if/bit/skip tag", tf
			}
			if bind+1 < len(m.fields) && (m.fields[bind+1].greedy || m.fields[bind+1].rest) {
				return nil, "Count 目标字段之后不得是 greedy 字段", m.fields[bind+1]
			}
			f.countTarget = bind
			tf.countBound = true
			tf.boundBy = i
		default:
			if i > 0 && m.fields[i-1].isWL {
				continue // WireLen 目标字段：形状已随前一个 WireLen 字段校验
			}
			if f.countBound {
				// Count 标记目标字段：形状已随前置 Count 字段校验，只校验元素
				if sl, ok := fieldType.Underlying().(*types.Slice); ok {
					if msg := g.validateTypeCtx(sl.Elem(), &fieldMeta{name: f.name}, name); msg != "" {
						return nil, msg, f
					}
				}
				continue
			}
			if f.count != "" {
				countIdx, ok := m.byName[f.count]
				if !ok || countIdx >= i {
					return nil, fmt.Sprintf("count 目标字段 %q 必须是同结构体中位于本字段之前的整型字段", f.count), f
				}
				ct := m.fields[countIdx].typ
				if !isIntKind(ct) {
					if p, ok := ct.Underlying().(*types.Pointer); !ok || !isIntKind(p.Elem()) {
						return nil, fmt.Sprintf("count 目标字段 %q 不是整型（或整型指针）", f.count), f
					}
				}
				isSlice := false
				isPtrToSlice := false
				if _, ok := fieldType.Underlying().(*types.Slice); ok {
					isSlice = true
				}
				if p, ok := fieldType.Underlying().(*types.Pointer); ok {
					if _, ok := p.Elem().Underlying().(*types.Slice); ok {
						isPtrToSlice = true
					}
				}
				if !isSlice && !isPtrToSlice {
					return nil, "count tag 只能用于 slice（或指向 slice 的指针）", f
				}
			}
			if f.greedy || f.rest {
				if f.greedy {
					u, ok := fieldType.Underlying().(*types.Slice)
					if !ok || !isUint8(u.Elem()) {
						return nil, "greedy tag 只能用于 []byte", f
					}
				}
				if i != len(m.fields)-1 {
					return nil, "greedy 字段只能出现在结构体末尾", f
				}
			}
			if f.hasBit {
				if f.hasCond {
					return nil, "bit 与 if 不能同时用于同一字段", f
				}
				if _, ok := fieldType.Underlying().(*types.Pointer); !ok {
					return nil, "bit tag 只能用于指针字段", f
				}
				// 声明序向前最近的前导整型字段作谓词（与 Count 向前扫描同一套绑定思路）
				pred := -1
				for j := i - 1; j >= 0; j-- {
					if _, _, _, ok := basicInfo(m.fields[j].typ); ok {
						pred = j
						break
					}
				}
				if pred == -1 {
					return nil, "bit 谓词字段缺失：声明序之前没有前导整型字段", f
				}
				pw, _, _, _ := basicInfo(m.fields[pred].typ)
				if f.bit >= pw*8 {
					return nil, fmt.Sprintf("bit 位号 %d 超出谓词字段 %s 的宽度（%d 字节）", f.bit, m.fields[pred].name, pw), f
				}
				f.bitPred = pred
			}
			if f.hasCond {
				condIdx, ok := m.byName[f.cond]
				if !ok || condIdx >= i {
					return nil, fmt.Sprintf("if 谓词字段 %q 必须是同结构体中位于本字段之前的整型字段", f.cond), f
				}
				if !isIntKind(m.fields[condIdx].typ) {
					return nil, fmt.Sprintf("if 谓词字段 %q 不是整型", f.cond), f
				}
				if _, ok := fieldType.Underlying().(*types.Pointer); !ok {
					return nil, "if tag 只能用于指针字段", f
				}
			}
			if msg := g.validateFieldType(f, name); msg != "" {
				return nil, msg, f
			}
		}
	}
	return m, "", nil
}

// validateFieldType 以字段上下文递归校验字段类型（旧 validateType 的移植，
// f 携带 count/greedy 信息——裸 slice 的报错在此分支）。
func (g *gen) validateFieldType(f *fieldMeta, stName string) string {
	return g.validateTypeCtx(f.typ, f, stName)
}

func (g *gen) validateTypeCtx(t types.Type, f *fieldMeta, stName string) string {
	if b, ok := t.Underlying().(*types.Basic); ok {
		switch b.Kind() {
		case types.Bool,
			types.Int8, types.Int16, types.Int32, types.Int64,
			types.Uint8, types.Uint16, types.Uint32, types.Uint64:
			return ""
		case types.Int, types.Uint:
			return "平台相关宽度的 int/uint 不支持，请用定宽类型"
		case types.String:
			return "string 不支持，请用 []byte（可配 greedy）"
		default:
			return fmt.Sprintf("不支持的类型 %s", b.Name())
		}
	}
	switch u := t.Underlying().(type) {
	case *types.Array:
		return g.validateTypeCtx(u.Elem(), &fieldMeta{name: f.name}, stName)
	case *types.Slice:
		if f.rest {
			return "" // codec.Rest：greedy 语义，无需 count/greedy tag
		}
		if f.greedy {
			return ""
		}
		if f.count != "" {
			return g.validateTypeCtx(u.Elem(), &fieldMeta{name: f.name}, stName)
		}
		return "slice 必须配 count 或 greedy tag"
	case *types.Pointer:
		if sl, ok := u.Elem().Underlying().(*types.Slice); ok && f.count != "" {
			// 指向 slice 的指针：count 挂在指针字段上，校验元素类型
			return g.validateTypeCtx(sl.Elem(), &fieldMeta{name: f.name}, stName)
		}
		return g.validateTypeCtx(u.Elem(), f, stName)
	case *types.Struct:
		nm := nestedStructName(t, f.name)
		_, msg, _ := g.validate(nm, u)
		return msg
	}
	return fmt.Sprintf("不支持的类型 %s", t.Underlying().String())
}

// fixedSize 移植：类型的静态定长；msg != "" 表示不定长或校验失败。
func (g *gen) fixedSize(t types.Type) (int, string) {
	if b, ok := t.Underlying().(*types.Basic); ok {
		switch b.Kind() {
		case types.Bool, types.Int8, types.Uint8:
			return 1, ""
		case types.Int16, types.Uint16:
			return 2, ""
		case types.Int32, types.Uint32:
			return 4, ""
		case types.Int64, types.Uint64:
			return 8, ""
		}
		return 0, fmt.Sprintf("类型 %s 不是定长类型", b.Name())
	}
	switch u := t.Underlying().(type) {
	case *types.Array:
		es, msg := g.fixedSize(u.Elem())
		if msg != "" {
			return 0, msg
		}
		return int(u.Len()) * es, ""
	case *types.Struct:
		nm := nestedStructName(t, "")
		meta, msg, _ := g.validate(nm, u)
		if msg != "" {
			return 0, msg
		}
		total := 0
		for _, f := range meta.fields {
			if f.hasSkip {
				total += f.skip
				continue
			}
			if f.isWL {
				return 0, "类型不是定长的（含 WireLen 长度前缀字段），不能作数组或列表元素"
			}
			if f.isCM {
				return 0, "类型不是定长的（含 Count 长度前缀字段），不能作数组或列表元素"
			}
			if f.hasCond || f.count != "" || f.greedy || f.countBound {
				return 0, "类型不是定长的（含条件/count/greedy 字段），不能作数组或列表元素"
			}
			es, msg := g.fixedSize(f.typ)
			if msg != "" {
				return 0, msg
			}
			total += es
		}
		return total, ""
	}
	return 0, fmt.Sprintf("类型 %s 不是定长类型", t.Underlying().String())
}

// elemOfPtr 取指针字段的元素类型。
func elemOfPtr(t types.Type) types.Type {
	if p, ok := t.Underlying().(*types.Pointer); ok {
		return p.Elem()
	}
	return t
}
